import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const file = new URL("../../Sources/KnarrCore/Resources/hird/extension.ts", import.meta.url);
const source = fs.readFileSync(file, "utf8").replace(/^import .*;\n/m, "").replace("export default function", "function install");
const handlers = new Map();
const policy = {compaction:{},lspTimeoutSeconds:10,verificationFeedback:{invalidCommand:"Run each verification separately.",repeatedFailure:"Diagnose the failing check before retrying.",failureThreshold:2}};
vm.runInNewContext(source+"\ninstall(pi)", {lookup:()=>({override(){}}), KNARR_HIRD_POLICY:policy, pi:{pi:{settings:{}},on:(n,f)=>handlers.set(n,f)}});
const result = handlers.get("tool_result");
assert.equal(typeof result, "function", "tool results must give immediate evidence feedback");
const event = (command,failed=false) => ({toolName:"bash",input:{command},details:{exitCode:failed?1:0},isError:failed,content:[{type:"text",text:"original result"}]});
const bad=event("swift test; echo done");
const feedback=await result(bad);
assert.equal(feedback.additionalContext,policy.verificationFeedback.invalidCommand);
assert.deepEqual(bad.content,[{type:"text",text:"original result"}]);
assert.equal(await result(event("swift test",true)),undefined);
assert.equal((await result(event("swift test",true))).additionalContext,policy.verificationFeedback.repeatedFailure);
await result(event("swift test"));
assert.equal(await result(event("swift test",true)),undefined,"successful command resets its failure streak");
assert.equal(await result(event("printf 'a;b'")),undefined,"quoted separators are not compound commands");
assert.equal(await result(event("rg 'swift test' README.md")),undefined);
assert.equal((await result(event("bash -lc 'swift test; echo done'")))?.additionalContext,policy.verificationFeedback.invalidCommand);
assert.equal((await result(event("eval 'swift test'")))?.additionalContext,policy.verificationFeedback.invalidCommand);
assert.equal((await result(event("source checks.sh")))?.additionalContext,policy.verificationFeedback.invalidCommand);
assert.equal((await result(event(". checks.sh")))?.additionalContext,policy.verificationFeedback.invalidCommand);
assert.equal(await result(event("env CHECK=1 swift test && swift build")),undefined);
console.log("Hird immediate evidence and retry feedback: PASS");
